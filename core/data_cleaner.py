def auto_suggest_column_codes(columns: list) -> list:
    """
    Analyzes raw survey column headers (often long question texts)
    and suggests concise, standardized academic variable codes (e.g. PE1, PU2, Age, Gender).
    
    Returns a list of suggested strings corresponding to each input column.
    """
    suggestions = []
    seen = {}
    
    for idx, raw_col in enumerate(columns):
        col_str = str(raw_col).strip()
        col_lower = col_str.lower()
        
        suggested = None
        
        # 1. Check for bracketed codes, e.g., "Câu hỏi... [PE1]" or "Câu hỏi (PU_2)"
        bracket_match = re.search(r'\[\s*([A-Za-z0-9_]{2,10})\s*\]', col_str)
        if bracket_match:
            suggested = bracket_match.group(1).upper()
            
        if not suggested:
            paren_match = re.search(r'\(\s*([A-Za-z0-9_]{2,10})\s*\)', col_str)
            if paren_match:
                candidate = paren_match.group(1).upper()
                # Don't pick up common Vietnamese words in parens like (Nam), (Nữ)
                if candidate not in ["NAM", "NU", "NỮ", "CO", "CÓ", "KHONG", "KHÔNG"]:
                    suggested = candidate

        # 2. Check for question prefix e.g., "Câu 1:", "Q1.", "Question 2"
        if not suggested:
            q_match = re.search(r'^(?:câu|q|question|item)\s*([0-9]+)', col_lower)
            if q_match:
                suggested = f"Q{q_match.group(1)}"

        # 3. Check for demographic keywords
        if not suggested:
            if any(k in col_lower for k in ["giới tính", "gender", "sex"]):
                suggested = "Gender"
            elif any(k in col_lower for k in ["độ tuổi", "tuổi", "age", "năm sinh"]):
                suggested = "Age"
            elif any(k in col_lower for k in ["thu nhập", "income", "lương"]):
                suggested = "Income"
            elif any(k in col_lower for k in ["học vấn", "education", "trình độ"]):
                suggested = "Education"
            elif any(k in col_lower for k in ["nghề nghiệp", "occupation", "job", "việc làm"]):
                suggested = "Occupation"
            elif any(k in col_lower for k in ["hôn nhân", "marital", "kết hôn"]):
                suggested = "MaritalStatus"
            elif any(k in col_lower for k in ["địa chỉ email", "email"]):
                suggested = "Email"
            elif any(k in col_lower for k in ["dấu thời gian", "timestamp"]):
                suggested = "Timestamp"

        # 4. If column is already short, valid code (e.g. PE1, BI2, F1, Age)
        if not suggested:
            clean_token = re.sub(r'[^A-Za-z0-9_]', '', col_str)
            if 1 <= len(clean_token) <= 10 and not any(c in col_str for c in [' ', '?', '!', ',', ';', ':', '/']):
                suggested = clean_token

        # 5. Fallback generic variable code
        if not suggested:
            suggested = f"VAR_{idx + 1}"

        # Ensure uniqueness
        if suggested in seen:
            seen[suggested] += 1
            unique_suggested = f"{suggested}_{seen[suggested]}"
        else:
            seen[suggested] = 1
            unique_suggested = suggested
            
        suggestions.append(unique_suggested)
        
    return suggestions


def detect_data_health(df: pd.DataFrame) -> dict:
    """
    Scans the dataset and returns a comprehensive data health diagnostic report:
    dimensions, duplicate rows, missing values, system metadata columns,
    and potential text Likert columns.
    """
    total_rows, total_cols = df.shape
    dup_count = int(df.duplicated().sum())
    
    # Missing cells
    missing_cells = int(df.isna().sum().sum())
    total_cells = total_rows * total_cols if total_rows * total_cols > 0 else 1
    missing_pct = (missing_cells / total_cells) * 100
    
    # Missing per column
    missing_series = df.isna().sum()
    cols_with_missing = missing_series[missing_series > 0]
    
    missing_rows = []
    for col, count in cols_with_missing.items():
        pct = (count / total_rows) * 100
        missing_rows.append({
            "Tên cột": col,
            "Số dòng khuyết": int(count),
            "Tỷ lệ khuyết (%)": round(pct, 2),
            "Kiểu dữ liệu": str(df[col].dtype)
        })
    missing_df = pd.DataFrame(missing_rows)
    if not missing_df.empty:
        missing_df = missing_df.sort_values(by="Số dòng khuyết", ascending=False)
        
    # Detect potential system/metadata columns
    system_cols = []
    for c in df.columns:
        c_lower = str(c).lower().strip()
        if any(kw in c_lower for kw in SYSTEM_COLUMN_KEYWORDS):
            system_cols.append(c)

    # Detect potential text Likert columns (object columns whose values match Likert keywords)
    likert_text_cols = []
    likert_keywords = ["đồng ý", "agree", "disagree", "trung lập", "neutral", "bình thường"]
    for c in df.columns:
        if df[c].dtype == object:
            # check non-null sample
            sample_vals = df[c].dropna().astype(str).str.lower().head(20).tolist()
            if sample_vals:
                matches = sum(1 for val in sample_vals if any(kw in val for kw in likert_keywords))
                if matches / len(sample_vals) >= 0.4:
                    likert_text_cols.append(c)
                    
    return {
        "total_rows": total_rows,
        "total_cols": total_cols,
        "duplicate_rows": dup_count,
        "missing_cells": missing_cells,
        "missing_pct": round(missing_pct, 2),
        "missing_columns_count": len(cols_with_missing),
        "missing_df": missing_df,
        "system_cols": system_cols,
        "likert_text_cols": likert_text_cols
    }


def clean_missing_values(df: pd.DataFrame, method: str = "drop_rows",
                         target_cols: list = None, threshold_pct: float = 50.0) -> tuple:
    """
    Handles missing values using academic research best practices:
    - 'drop_rows': Listwise deletion of rows containing missing values in target_cols.
    - 'drop_cols': Drop columns with missing rate exceeding threshold_pct.
    - 'impute_mean': Impute numeric columns with column mean.
    - 'impute_median': Impute numeric columns with column median.
    - 'impute_mode': Impute categorical columns with column mode (most frequent value).
    
    Returns: (cleaned_df, message)
    """
    df_clean = df.copy()
    initial_rows, initial_cols = df_clean.shape
    cols = target_cols if target_cols else list(df_clean.columns)

    if method == "drop_rows":
        df_clean = df_clean.dropna(subset=cols)
        removed = initial_rows - len(df_clean)
        msg = f"Đã loại bỏ {removed} dòng chứa giá trị khuyết (Cỡ mẫu còn N = {len(df_clean):,})."

    elif method == "drop_cols":
        threshold = threshold_pct / 100.0
        cols_to_drop = [c for c in cols if (df_clean[c].isna().sum() / initial_rows) > threshold]
        df_clean = df_clean.drop(columns=cols_to_drop)
        msg = f"Đã loại bỏ {len(cols_to_drop)} cột có tỷ lệ khuyết > {threshold_pct}% ({', '.join(cols_to_drop)})."

    elif method == "impute_mean":
        imputed_count = 0
        for c in cols:
            if pd.api.types.is_numeric_dtype(df_clean[c]):
                mean_val = df_clean[c].mean()
                if df_clean[c].isna().sum() > 0:
                    df_clean[c] = df_clean[c].fillna(mean_val)
                    imputed_count += 1
        msg = f"Đã điền giá trị trung bình (Mean) cho {imputed_count} biến định lượng."

    elif method == "impute_median":
        imputed_count = 0
        for c in cols:
            if pd.api.types.is_numeric_dtype(df_clean[c]):
                med_val = df_clean[c].median()
                if df_clean[c].isna().sum() > 0:
                    df_clean[c] = df_clean[c].fillna(med_val)
                    imputed_count += 1
        msg = f"Đã điền giá trị trung vị (Median) cho {imputed_count} biến định lượng."

    elif method == "impute_mode":
        imputed_count = 0
        for c in cols:
            mode_series = df_clean[c].mode()
            if not mode_series.empty and df_clean[c].isna().sum() > 0:
                df_clean[c] = df_clean[c].fillna(mode_series[0])
                imputed_count += 1
        msg = f"Đã điền giá trị yếu vị (Mode) cho {imputed_count} biến."
    else:
        msg = "Phương thức xử lý không hợp lệ."

    return df_clean, msg


def clean_duplicates(df: pd.DataFrame, subset: list = None) -> tuple:
    """
    Removes exact duplicate rows or duplicates on specific identifier columns.
    Returns: (cleaned_df, removed_count)
    """
    df_clean = df.copy()
    initial_n = len(df_clean)
    df_clean = df_clean.drop_duplicates(subset=subset, keep='first')
    removed = initial_n - len(df_clean)
    return df_clean, removed


def clean_outliers(df: pd.DataFrame, target_cols: list, method: str = "clip",
                   min_val: float = 1.0, max_val: float = 5.0,
                   z_threshold: float = 3.0) -> tuple:
    """
    Detects and treats outliers in numerical survey items:
    - 'clip': Clamps/winsorizes values to [min_val, max_val] (standard for 1-5 or 1-7 Likert scales).
    - 'drop_zscore': Listwise deletion of rows where |Z| > z_threshold.
    
    Returns: (cleaned_df, message)
    """
    df_clean = df.copy()
    num_cols = [c for c in target_cols if pd.api.types.is_numeric_dtype(df_clean[c])]

    if method == "clip":
        for c in num_cols:
            df_clean[c] = df_clean[c].clip(lower=min_val, upper=max_val)
        return df_clean, f"Đã giới hạn (Clip) tất cả giá trị của {len(num_cols)} biến về khoảng hợp lệ [{min_val}, {max_val}]."

    elif method == "drop_zscore":
        initial_len = len(df_clean)
        mask = pd.Series(True, index=df_clean.index)
        for c in num_cols:
            std = df_clean[c].std()
            if std > 0:
                z = (df_clean[c] - df_clean[c].mean()).abs() / std
                mask = mask & (z <= z_threshold)
        df_clean = df_clean[mask]
        removed = initial_len - len(df_clean)
        return df_clean, f"Đã loại bỏ {removed} dòng chứa giá trị dị biệt (|Z| > {z_threshold}) trong {len(num_cols)} biến."

    return df_clean, "Không có thay đổi."


def recode_column_values(df: pd.DataFrame, col: str, mapping: dict) -> pd.DataFrame:
    """
    Recodes text values in a column to numeric codes based on mapping dictionary.
    Performs case-insensitive and whitespace-stripped matching for resilience.
    """
    df_clean = df.copy()
    if col not in df_clean.columns:
        return df_clean

    # Lowercase clean mapping
    normalized_map = {str(k).lower().strip(): v for k, v in mapping.items()}

    def mapper(val):
        if pd.isna(val):
            return np.nan
        val_str = str(val).lower().strip()
        if val_str in normalized_map:
            return normalized_map[val_str]
        # Try direct match
        try:
            return float(val)
        except Exception:
            return val

    df_clean[col] = df_clean[col].apply(mapper)
    # Convert to numeric if possible
    try:
        df_clean[col] = pd.to_numeric(df_clean[col])
    except Exception:
        pass

    return df_clean


def generate_codebook(df: pd.DataFrame, variable_labels: dict = None,
                      value_labels: dict = None, measure_types: dict = None) -> pd.DataFrame:
    """
    Constructs a comprehensive research codebook (Data Dictionary):
    Column Code, Original Question / Label, Measurement Scale, Data Type,
    Valid Count, Missing Count, Missing %, Min, Max, Mean, SD, Value Labels.
    """
    v_labels = variable_labels if variable_labels else {}
    val_labels = value_labels if value_labels else {}
    m_types = measure_types if measure_types else {}

    rows = []
    total_n = len(df)

    for col in df.columns:
        series = df[col]
        label = v_labels.get(col, col)
        measure = m_types.get(col, "Scale" if pd.api.types.is_numeric_dtype(series) else "Nominal")
        dtype_str = str(series.dtype)

        missing_count = int(series.isna().sum())
        valid_count = total_n - missing_count
        missing_pct = (missing_count / total_n) * 100 if total_n > 0 else 0

        # Numeric stats
        if pd.api.types.is_numeric_dtype(series) and valid_count > 0:
            min_val = round(float(series.min()), 2)
            max_val = round(float(series.max()), 2)
            mean_val = round(float(series.mean()), 2)
            sd_val = round(float(series.std()), 2) if valid_count > 1 else 0.0
        else:
            min_val = "-"
            max_val = "-"
            mean_val = "-"
            sd_val = "-"

        # Value mapping samples
        val_mapping_str = ""
        if col in val_labels and val_labels[col]:
            val_mapping_str = ", ".join([f"{k}={v}" for k, v in list(val_labels[col].items())[:4]])
            if len(val_labels[col]) > 4:
                val_mapping_str += "..."
        else:
            uniques = series.dropna().unique()
            if len(uniques) <= 6:
                val_mapping_str = ", ".join([str(x) for x in uniques])
            else:
                val_mapping_str = ", ".join([str(x) for x in uniques[:3]]) + "..."

        rows.append({
            "Mã biến (Variable Code)": col,
            "Nội dung câu hỏi / Nhãn gốc (Label)": label,
            "Thang đo (Measure)": str(measure).capitalize(),
            "Kiểu dữ liệu (Dtype)": dtype_str,
            "Mẫu hợp lệ (N)": valid_count,
            "Dòng khuyết": missing_count,
            "Tỷ lệ khuyết (%)": f"{missing_pct:.1f}%",
            "Min": min_val,
            "Max": max_val,
            "Mean": mean_val,
            "SD": sd_val,
            "Mẫu giá trị / Nhãn": val_mapping_str
        })

    return pd.DataFrame(rows)


def export_cleaned_dataset_excel(df: pd.DataFrame, variable_labels: dict = None,
                                 value_labels: dict = None,
                                 measure_types: dict = None) -> io.BytesIO:
    """
    Exports the cleaned dataset into an academic-standard Excel file (.xlsx) with 2 sheets:
    - Sheet 1: 'Du_lieu_sach' - The complete cleaned data table.
    - Sheet 2: 'Tu_dien_bien_Codebook' - Complete research codebook with variables, original questions, scales.
    """
    codebook_df = generate_codebook(df, variable_labels, value_labels, measure_types)
    output = io.BytesIO()

    with pd.ExcelWriter(output, engine='openpyxl') as writer:
        df.to_excel(writer, sheet_name="Du_lieu_sach", index=False)
        codebook_df.to_excel(writer, sheet_name="Tu_dien_bien_Codebook", index=False)

        # Style the sheets with openpyxl
        try:
            from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
            from openpyxl.utils import get_column_letter

            wb = writer.book

            header_font = Font(name="Calibri", size=11, bold=True, color="FFFFFF")
            header_fill = PatternFill(start_color="1E3A8A", end_color="1E3A8A", fill_type="solid")
            thin_border = Border(
                left=Side(style='thin', color='CBD5E1'),
                right=Side(style='thin', color='CBD5E1'),
                top=Side(style='thin', color='CBD5E1'),
                bottom=Side(style='thin', color='CBD5E1')
            )

            for ws in wb.worksheets:
                ws.views.sheetView[0].showGridLines = True
                # Format header row
                for cell in ws[1]:
                    cell.font = header_font
                    cell.fill = header_fill
                    cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)

                # Set auto column width
                for col in ws.columns:
                    col_letter = get_column_letter(col[0].column)
                    max_len = max(len(str(cell.value or '')) for cell in col[:150])
                    ws.column_dimensions[col_letter].width = min(max(max_len + 3, 12), 50)
        except Exception:
            pass

    output.seek(0)
    return output
